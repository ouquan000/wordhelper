import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const adb='C:/Program Files/ASUS/GlideX/adb.exe';
const serial='emulator-5554', pkg='com.kaoyan.wordhelper';
const target='files/datastore/user_settings.preferences_pb';
const temp='files/datastore/user_settings.preferences_pb.wb-repair.tmp';
const deviceStage='/data/local/tmp/wb-repair-prefs-20261107.pb';
const root=path.dirname(fileURLToPath(import.meta.url));
const call=(...args)=>execFileSync(adb,['-s',serial,...args],{timeout:8000,maxBuffer:1024*1024});
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const oldValue=Buffer.from('10.0.2.2:8790'), newValue=Buffer.from('10.0.2.2:8765');
if(call('get-state').toString().trim()!=='device') throw new Error('Expected emulator is not online');
const initial=call('exec-out','run-as',pkg,'cat',target);
if(initial.indexOf(oldValue)<0 || initial.indexOf(oldValue)!==initial.lastIndexOf(oldValue)) throw new Error('Expected unique old address not found; no changes');
const mode=call('shell','run-as',pkg,'stat','-c','%a',target).toString().trim();
if(!/^[0-7]{3,4}$/.test(mode)) throw new Error('Unexpected preferences mode');
call('shell','am','force-stop',pkg);
const before=call('exec-out','run-as',pkg,'cat',target);
if(!before.equals(initial)) throw new Error('Preferences changed during stop; inspect before changing settings');
const after=Buffer.from(before);
newValue.copy(after,before.indexOf(oldValue));
const restored=Buffer.from(after); oldValue.copy(restored,after.indexOf(newValue));
if(!restored.equals(before) || before.length!==after.length) throw new Error('Unexpected binary edit');
const backup=path.join(root,'emulator-prefs-before.pb');
const staged=path.join(root,'emulator-prefs-migrated.pb');
fs.writeFileSync(backup,before,{flag:'wx'});
fs.writeFileSync(staged,after,{flag:'wx'});
try {
  call('push',staged,deviceStage);
  call('shell','run-as',pkg,'cp',deviceStage,temp);
  call('shell','run-as',pkg,'chmod',mode,temp);
  call('shell','run-as',pkg,'mv',temp,target);
  const verified=call('exec-out','run-as',pkg,'cat',target);
  if(!verified.equals(after)) throw new Error('Device readback does not match intended exact edit');
  const result={at:new Date().toISOString(),serial,package:pkg,setting:'card_back_url',before:'10.0.2.2:8790',after:'10.0.2.2:8765',bytes:before.length,beforeSha256:hash(before),afterSha256:hash(verified),originalMode:mode,verifiedMode:call('shell','run-as',pkg,'stat','-c','%a',target).toString().trim(),otherBytesUnchanged:true,appRestarted:false,realPhoneTouched:false,learningDataTouched:false};
  fs.writeFileSync(path.join(root,'emulator-address-evidence.json'),JSON.stringify(result,null,2)+'\n',{flag:'wx'});
  console.log(JSON.stringify(result,null,2));
} finally {
  call('shell','rm','-f',deviceStage);
  fs.unlinkSync(staged);
}
